"""Render 8 anchored isometric directions; assemble compact 40-cell RGBA atlases.
Usage: blender -b art-src/blender/bailiff-isometric.blend --python scripts/blender/render_bailiff.py
Optional: -- --direction 0 (0..7) or --preview (one idle frame).
"""
import bpy, math, pathlib, json, subprocess, sys, argparse
from bpy_extras.object_utils import world_to_camera_view
from mathutils import Vector
ROOT=pathlib.Path(__file__).resolve().parents[2]
parser=argparse.ArgumentParser();parser.add_argument('--direction',type=int);parser.add_argument('--preview',action='store_true');parser.add_argument('--timer',action='store_true')
args=parser.parse_args(sys.argv[sys.argv.index('--')+1:] if '--' in sys.argv else [])
s=bpy.context.scene;r=bpy.data.objects['BailiffRig']
s.render.resolution_x=256;s.render.resolution_y=256;s.render.resolution_percentage=100
s.render.film_transparent=True;s.render.image_settings.file_format='PNG';s.render.image_settings.color_mode='RGBA'
s.render.image_settings.color_depth='8';s.render.image_settings.compression=75
s.render.threads_mode='FIXED';s.render.threads=4
# Fixed camera and lighting for every pose/direction: never auto-crop frames.
animations=[('idle','Idle',8,12,True),('attack','Attack',10,12,False),('walk','Walk',8,12,True),('hurt','Hurt',4,12,False),('death','Death',10,10,False)]
OUT=ROOT/'assets/bosses/bailiff_iso';OUT.mkdir(parents=True,exist_ok=True)
FRAMES=ROOT/'art-src/bailiff-frames';FRAMES.mkdir(parents=True,exist_ok=True)
anchor=world_to_camera_view(s,s.camera,Vector((0,0,0)))
metadata={'character':'The Ash Bailiff','version':1,'frame_width':256,'frame_height':256,'columns':8,'rows':5,'anchor_x':round(anchor.x*256),'anchor_y':round((1-anchor.y)*256),'display_scale':.55,'camera':{'projection':'orthographic','elevation_degrees':30,'azimuth_degrees':45,'ortho_scale':3.5},'direction_order':['southwest','south','southeast','east','northeast','north','northwest','west'],'direction_angles':[i*45 for i in range(8)],'direction_pattern':'bailiff_y%03d.png','animations':{}}
offset=0
for name,action,count,fps,loop in animations:
    metadata['animations'][name]={'offset':offset,'frames':count,'fps':fps,'loop':loop};offset+=count
def render_jobs():
    for d in ([args.direction] if args.direction is not None else range(8)):
        if d not in range(8):raise ValueError('direction must be 0..7')
        r.rotation_euler.z=math.radians(d*45)
        folder=FRAMES/('y%03d'%(d*45));folder.mkdir(exist_ok=True)
        framepaths=[]
        for name,action,count,fps,loop in animations:
            r.animation_data.action=bpy.data.actions['Refined_'+action]
            for frame in range(1,count+1):
                s.frame_set(frame);p=folder/(name+'_%02d.png'%frame);s.render.filepath=str(p)
                bpy.ops.render.render(write_still=True);framepaths.append(str(p))
                yield {'direction':d,'animation':name,'frame':frame,'completed':len(framepaths)+d*40,'total':320}
                if args.preview:
                    print('PREVIEW',str(p),flush=True);sys.exit(0)
            print('ANIMATION_DONE',d,name,flush=True)
        subprocess.run(['magick','montage',*framepaths,'-background','none','-tile','8x5','-geometry','256x256+0+0',str(OUT/('bailiff_y%03d.png'%(d*45)))],check=True)
        print('DIRECTION_DONE',d,flush=True)
    (OUT/'bailiff.json').write_text(json.dumps(metadata,indent=2)+'\n')
    # Runtime Lua data avoids bringing in another JSON parser or loading .blend sources.
    lines=['-- Generated by scripts/blender/render_bailiff.py; fixed anchors and packed cell offsets.','return {',"  path = 'assets/bosses/bailiff_iso/',",'  width = 256, height = 256, columns = 8, rows = 5,',f"  anchorX = {metadata['anchor_x']}, anchorY = {metadata['anchor_y']}, scale = 0.55,",'  animations = {']
    for name,action,count,fps,loop in animations:
        a=metadata['animations'][name];lines.append(f"    {name} = {{ offset = {a['offset']}, frames = {count}, fps = {fps}, loop = {str(loop).lower()} }},")
    lines+=['  },','}'];(ROOT/'src/data/bailiff_sprite.lua').write_text('\n'.join(lines)+'\n')
    r.rotation_euler.z=0;r.animation_data.action=bpy.data.actions['Refined_Idle'];s.frame_set(1)
    print('ALL_SHEETS_DONE',metadata['anchor_x'],metadata['anchor_y'],flush=True)
    yield {'done':True,'completed':320,'total':320}

jobs=render_jobs()
progress=ROOT/'art-src/bailiff-render-progress.json'
def step():
    try:
        state=next(jobs);progress.write_text(json.dumps(state))
        return None if state.get('done') else .05
    except StopIteration:
        return None
    except Exception as e:
        progress.write_text(json.dumps({'error':str(e)}));raise
if args.timer:
    bpy.app.timers.register(step,first_interval=.1)
    print('RENDER_SCHEDULED',flush=True)
else:
    for state in jobs:
        progress.write_text(json.dumps(state))
